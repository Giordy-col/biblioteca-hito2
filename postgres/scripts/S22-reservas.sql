-- Vista de apoyo: las reservas con nombres, en orden
CREATE VIEW agenda AS
SELECT r.id, s.nombre AS sala, e.nombre AS estudiante,
       to_char(r.inicio, 'Dy DD/MM HH24:MI') AS inicio,
       to_char(r.fin, 'HH24:MI') AS fin,
       r.asistentes, r.estado
FROM   reserva r
JOIN   sala s       USING (id_sala)
JOIN   estudiante e USING (codigo)
ORDER BY r.inicio, s.nombre;

SELECT * FROM agenda;
