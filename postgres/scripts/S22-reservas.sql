DROP SCHEMA IF EXISTS reservas CASCADE;
CREATE SCHEMA reservas;
SET search_path TO reservas;

-- dia(n): el día n de la próxima semana (1 = lunes ... 7 = domingo)
CREATE FUNCTION dia(n integer) RETURNS date
LANGUAGE sql STABLE
AS $$
    SELECT (date_trunc('week', CURRENT_DATE) + interval '7 days')::date + (n - 1);
$$;

CREATE TABLE sala (
    id_sala    integer      PRIMARY KEY,
    nombre     varchar(40)  NOT NULL UNIQUE,
    capacidad  integer      NOT NULL CHECK (capacidad > 0),
    activa     boolean      NOT NULL DEFAULT true      -- false = en mantenimiento
);

-- Recursos de cada sala (tablero, pantalla, ...): atributo multivaluado
CREATE TABLE sala_recurso (
    id_sala  integer      REFERENCES sala,
    recurso  varchar(40),
    PRIMARY KEY (id_sala, recurso)
);

CREATE TABLE estudiante (
    codigo            varchar(10)   PRIMARY KEY,
    nombre            varchar(80)   NOT NULL,
    correo            varchar(120)  NOT NULL UNIQUE,
    sancionado_hasta  date                       -- NULL = sin sanción
);

CREATE TABLE reserva (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sala     integer      NOT NULL REFERENCES sala,
    codigo      varchar(10)  NOT NULL REFERENCES estudiante,
    inicio      timestamp    NOT NULL,
    fin         timestamp    NOT NULL,
    asistentes  integer      NOT NULL,
    estado      varchar(12)  NOT NULL DEFAULT 'activa'
                CHECK (estado IN ('activa', 'cancelada', 'cumplida', 'no_asistio'))
);

